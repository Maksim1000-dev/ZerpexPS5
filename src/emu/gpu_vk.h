// ZerpexPS5 — фаза 5: интерфейс Vulkan-слоя (реализация в gpu_vk.cpp)
//
// gpu.cpp (HLE по именам импортов) пользуется только этими четырьмя
// функциями. Vulkan грузится динамически (vulkan-1.dll из System32),
// линковки нет; если SDK-хедеров нет — сборка не падает, слой честно
// отчитывается, что работать не будет.
// ============================================================================
#pragma once

#include <cstdint>

namespace zrx {
namespace gpu_vk {

// Готовит (лениво и идемпотентно) окно + instance + device + свапчейн +
// оффскрин-изображение и staging-буфер под кадр frameBytes байт.
// false = Vulkan недоступен (нет DLL или устройств) — гость продолжит,
// но кадров выводиться не будет (в логе честное объяснение).
bool Prepare(uint32_t w, uint32_t h, uint64_t frameBytes);

// Указатель на staging-буфер (persistently mapped) и его размер.
// Кадр гость рисует у себя, gpu.cpp копирует его сюда НАПРЯМУЮ.
void* StagePtr(uint64_t* sizeOut);

// Копия staging -> оффскрин -> картинка свапчейна -> present.
// bytes должен быть не больше размера staging.
bool Present(uint32_t w, uint32_t h, uint64_t bytes);

// Полная уборка: device, instance, окно, DLL.
void Shutdown();

// Приоритет видеокарты (индекс из перечисления Vulkan; -1 = авто).
// Задаётся параметром --gpu N — лаунчер передаёт выбор из настроек.
void SetPreferredDevice(int index);

// Изолированные эксперименты инициализации Vulkan (--vkprobe N): без гостя,
// без VEH, без нашего аллокатора — чистый Vulkan + печать каждого шага.
// Возвращает 0 при успехе; краш ловит фильтр main.cpp (модуль + стек).
int Probe(int which);

// true, если Vulkan-устройство реально найдено (для честных сообщений)
bool DeviceAlive();

} } // namespace zrx::gpu_vk
