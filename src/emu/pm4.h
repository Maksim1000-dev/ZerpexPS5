// ============================================================================
// ZerpexPS5 — фаза 5.1 (шаг 1): разведка PM4
//
// PS5-игры не рисуют CPU-записью в буфер (как hello3), а гоняют через драйвер
// командные буферы с пакетами PM4 (AMD GCN-семейство). Этот модуль честно
// разбирает поток и печатает, что увидел: опкоды, регистры, вложенные буферы.
//
// ВАЖНО: это разведка. Рендер из PM4 в Vulkan — следующий шаг (5.2); сейчас мы
// ничего не рисуем из команд и ничего не выдумываем: неизвестные опкоды
// печатаются как hex. Имена опкодов — по открытым GCN-документам (mesa и др.).
// ============================================================================
#pragma once
#include <cstdint>

namespace zrx { namespace pm4 {

// Достаёт хост-указатель на гостевую память (для вложенных INDIRECT_BUFFER).
// Возвращает nullptr, если память не принадлежит гостю.
typedef const uint32_t* (*ResolveFn)(uint64_t guestAddr, uint64_t bytes,
                                     void* user);

// Кадровая сводка (фаза 5.2): что парсер увидел в потоке за прогон.
// Пока честно только про DRAW_INDEX_AUTO — реальное исполнение PM4 впереди.
struct Frame {
    bool     hasDraw   = false;   // встречен DRAW-пакет
    uint32_t drawCount = 0;       // вершин в последнем DRAW-пакете
};

// Разбирает ndwords dword'ов и печатает пакет. depth — уровень вложенности
// (рекурсия в INDIRECT_BUFFER, не глубже 2). resolve может быть nullptr —
// тогда вложенные буферы печатаются только адресом. frame (если не nullptr)
// заполняется сводкой виденных пакетов.
void DumpStream(const char* label, const uint32_t* d, uint32_t ndwords,
                int depth, ResolveFn resolve, void* user,
                Frame* frame = nullptr);

} } // namespace zrx::pm4
