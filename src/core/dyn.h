// ============================================================================
// ZerpexPS5 — фаза 4: динамические релокации ELF (PT_DYNAMIC)
//
// Что делает:
//   - разбирает PT_DYNAMIC мапнутого образа (уже в гостевой памяти);
//   - применяет RELA: RELATIVE, GLOB_DAT, _64, JUMP_SLOT, IRELATIVE;
//   - неразрешённые импорты получает диагностическую заглушку: вызов такой
//     функции ловится VEH'ом, в лог падает ИМЯ символа, гость получает 0.
//     Это честный диагноз "какой импорт не реализован", а не молчаливый краш.
//
// Образ грузится по своим vaddr (база 0), поэтому S = st_value напрямую.
// ============================================================================
#pragma once

#include <cstdint>

#include "elf.h"
#include "mem.h"

namespace zrx {
namespace dyn {

// Связывает модуль с памятью (нужно и для релокаций, и для страницы заглушек)
void AttachMemory(Memory* mem);

// Сбрасывает реестр заглушек (перед новым прогоном)
void ResetStubs();

// Применяет релокации по PT_DYNAMIC образа. Логирует сводку по типам
// и первые неразрешённые символы. Возвращает false при фатальной ошибке.
bool ApplyRelocations(const ElfImage& elf);

// VEH: проверить, является ли UD2 по адресу rip "хвостом" нашей заглушки
// (mov eax, idx; ud2). Возвращает имя символа через nameOut.
bool TryResolveStub(uint64_t rip, const char** nameOut);

} } // namespace zrx::dyn
